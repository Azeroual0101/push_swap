#include "libft.h"

size_t	ft_strlcpy(char *dest, const char *src, size_t size)
{
	size_t	i;
	size_t	len_src;

	if (!src)
	{
		if (size > 0)
			dest[0] = '\0';
		return (0);
	}
	len_src = ft_strlen(src);
	if (size == 0)
		return (len_src);
	i = 0;
	if (size != 0)
	{
		while (src [i] != '\0' && i < (size - 1))
		{
			dest[i] = src[i];
			i++;
		}
		dest[i] = '\0';
	}
	return (len_src);
}
