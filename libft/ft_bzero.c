#include "libft.h"

void	ft_bzero(void *b, size_t len)
{
	unsigned char	*temp;
	size_t			i;

	temp = (unsigned char *)b;
	i = 0;
	while (i < len)
	{
		temp[i] = 0;
		i++;
	}
}
